/** Render a fallback or injected version. Allocation belongs to shared CI, never this adapter. */
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const git = (source, ...args) => execFileSync('git', args, {
  cwd: source, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'],
}).trim();

export function publicVersion(value) {
  if (typeof value !== 'string' || !/^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$/.test(value)) {
    throw new Error('A public version must be strict major.minor.patch without a v prefix.');
  }
  return value;
}

export function renderBuildStamp(build) {
  return '/** GENERATED by npm run stamp or the CI build adapter. Public version and cache generation are separate. */\n'
    + 'export const BUILD = Object.freeze(' + JSON.stringify(build, null, 2) + ');\n';
}

async function fallbackVersion(source) {
  try { return JSON.parse(await readFile(join(source, 'package.json'), 'utf8')).version; }
  catch (error) {
    if (error.code !== 'ENOENT') throw error;
    return JSON.parse(await readFile(join(root, 'package.json'), 'utf8')).version;
  }
}

async function previousProvenance(source) {
  const text = await readFile(join(source, 'assets/js/version.js'), 'utf8');
  return Object.fromEntries(['branch', 'commit', 'date'].map(key => [
    key, text.match(new RegExp('["\']?' + key + '["\']?\\s*:\\s*["\']([^"\']+)["\']'))?.[1],
  ]));
}

export async function buildStamp({ source = root, version, branch, revision, date } = {}) {
  const chosen = publicVersion(version ?? await fallbackVersion(source));
  const worker = await readFile(join(source, 'sw.js'), 'utf8');
  const cacheGeneration = worker.match(/^const CACHE_VERSION = '(v[0-9]+)';$/m)?.[1];
  if (!cacheGeneration) throw new Error('The source worker must retain its technical cache baseline.');
  let commit = revision;
  try {
    commit ??= git(source, 'rev-parse', 'HEAD');
    branch ??= git(source, 'branch', '--remotes', '--contains', commit).split('\n')
      .map(line => line.trim().replace(/^origin\//, ''))
      .find(name => name === 'main') || git(source, 'rev-parse', '--abbrev-ref', 'HEAD');
    date ??= git(source, 'log', '-1', '--format=%ad', '--date=short', commit);
  } catch {
    const previous = await previousProvenance(source);
    commit ??= previous.commit; branch ??= previous.branch; date ??= previous.date;
  }
  if (!/^[a-f0-9]{7,40}$/.test(commit ?? '') || !/^\d{4}-\d{2}-\d{2}$/.test(date ?? '') || !branch) {
    throw new Error('The version stamp needs verifiable source provenance.');
  }
  return { version: chosen, cacheGeneration, branch, commit, date };
}

export async function stampSiteVersion({ source = root, target, ...options }) {
  const build = await buildStamp({ source, ...options });
  const page = join(target, 'index.html');
  const markup = await readFile(page, 'utf8');
  const footer = /(<span id="footer-version">)[^<]*(<\/span>)/g;
  if ([...markup.matchAll(footer)].length !== 1) throw new Error('The application shell needs one visible version footer.');
  await writeFile(page, markup.replace(footer, '$1v' + build.version + '$2'));
  for (const file of ['manifest.webmanifest', 'manifest.fr.webmanifest']) {
    const path = join(target, file);
    const manifest = JSON.parse(await readFile(path, 'utf8'));
    manifest.version = build.version;
    await writeFile(path, JSON.stringify(manifest, null, 2) + '\n');
  }
  await writeFile(join(target, 'assets/js/version.js'), renderBuildStamp(build));
  return build;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const build = await buildStamp();
  await writeFile(join(root, 'assets/js/version.js'), renderBuildStamp(build));
  console.log('Stamped local fallback ' + build.version + '; cache baseline ' + build.cacheGeneration + '.');
}
